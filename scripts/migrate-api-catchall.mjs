/**
 * migrate-api-catchall.mjs
 * 把 app/api/<group> 目录下所有 route.ts 原样搬到 lib/api-handlers/<group>/，并生成 catch-all 分发器。
 * 目的：把 Hobby 套餐 12 个 Serverless Functions 上限内（81 个 API 函数 → 8 个 catch-all）。
 *
 * 用法：
 *   node scripts/migrate-api-catchall.mjs            # 全量（不含 originkit，originkit 单独处理）
 *   node scripts/migrate-api-catchall.mjs auth        # 只处理 auth 组（样板验证）
 *
 * 组映射：brain/ai/auth/brand/projects/knowledge 按顶层目录；account/agents/component-source/skill-content/user → other（兜底 /api/[[...path]]）
 * originkit 由 --originkit 单独合并（两个 catch-all → 一个，按 path[0] 分发 genius/wexo）
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(process.cwd());
const SRC = path.join(ROOT, "app", "api");
const DST = path.join(ROOT, "lib", "api-handlers");

const GROUPS = {
  brain: "brain",
  ai: "ai",
  auth: "auth",
  brand: "brand",
  projects: "projects",
  knowledge: "knowledge",
  // 其余顶层目录 → other（兜底 catch-all app/api/[[...path]]）
};
const OTHER_TOP = ["account", "agents", "component-source", "skill-content", "user"];
const METHOD_RE = /^export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE)\b/gm;

function collectRoutes(groupDir) {
  const out = [];
  const walk = (dir, rel) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      if (ent.isDirectory()) {
        if (ent.name === "[[...path]]") continue; // 跳过分发器自身
        walk(path.join(dir, ent.name), path.join(rel, ent.name));
      } else if (ent.name === "route.ts") out.push(path.join(dir, ent.name));
    }
  };
  if (fs.existsSync(groupDir)) walk(groupDir, "");
  return out;
}

function methodsOf(file) {
  const src = fs.readFileSync(file, "utf8");
  const methods = [];
  for (const m of src.matchAll(METHOD_RE)) methods.push(m[1]);
  return methods;
}

/** 相对 app/api 的路径：app/api/auth/login/route.ts → auth/login */
function relKey(file, top) {
  const rel = path.relative(SRC, file).replaceAll(path.sep, "/"); // auth/login/route.ts
  return rel.slice(0, -"/route.ts".length); // auth/login
}

/** 生成 catch-all 分发器源码 */
function dispatcherSource(top, entries) {
  const imports = entries
    .map((e, i) => `import * as m${i} from "@/lib/api-handlers/${e.group}/${e.modPath}";`)
    .join("\n");
  const routes = entries
    .map(
      (e, i) =>
        `  { key: ${JSON.stringify(e.key)}, methods: { ${e.methods.map((m) => `${m}: m${i}.${m} as HandlerFn`).join(", ")} } },`,
    )
    .join("\n");
  const prefix = top === "other" ? "" : `${top}/`;
  return `// AUTO-GENERATED by scripts/migrate-api-catchall.mjs — DO NOT EDIT
// ${prefix}... 路由分发器：把 ${entries.length} 个原 route.ts 合并为 1 个 Serverless Function。
// URL 与行为保持不变；仅用于满足 Vercel Hobby 12 函数上限。
import { NextRequest, NextResponse } from "next/server";
${imports}

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type HandlerFn = (req: NextRequest, ctx?: unknown) => Promise<Response> | Response;
type Method = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
interface RouteDef {
  key: string;
  methods: Partial<Record<Method, HandlerFn>>;
}

const ROUTES: RouteDef[] = [
${routes}
];

/** 精确匹配优先，其次 [id] 动态段匹配；返回参数表 */
function matchRoute(path: string[]): { def: RouteDef; params: Record<string, string> } | null {
  const key = path.join("/");
  for (const def of ROUTES) {
    if (def.key === key) return { def, params: {} };
  }
  for (const def of ROUTES) {
    const parts = def.key.split("/");
    if (parts.length !== path.length) continue;
    const params: Record<string, string> = {};
    let ok = true;
    for (let i = 0; i < parts.length; i++) {
      const m = parts[i].match(/^\\[([^\\]]+)\\]$/);
      if (m) params[m[1]] = decodeURIComponent(path[i]);
      else if (parts[i] !== path[i]) {
        ok = false;
        break;
      }
    }
    if (ok) return { def, params };
  }
  return null;
}

async function dispatch(
  method: Method,
  req: NextRequest,
  ctx: { params: Promise<{ path: string[] }> },
): Promise<Response> {
  const { path: p } = await ctx.params;
  const hit = matchRoute(p);
  if (!hit) {
    return NextResponse.json({ error: "not_found", message: "接口不存在" }, { status: 404 });
  }
  const fn = hit.def.methods[method];
  if (!fn) {
    return NextResponse.json({ error: "method_not_allowed", message: "方法不支持" }, { status: 405 });
  }
  return fn(req, { params: Promise.resolve(hit.params) }) as Promise<Response>;
}

export const GET = (req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) => dispatch("GET", req, ctx);
export const POST = (req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) => dispatch("POST", req, ctx);
export const PUT = (req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) => dispatch("PUT", req, ctx);
export const PATCH = (req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) => dispatch("PATCH", req, ctx);
export const DELETE = (req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) => dispatch("DELETE", req, ctx);
`;
}

function run() {
  const onlyGroup = process.argv.slice(2).find((a) => !a.startsWith("--"));
  const doOriginkit = process.argv.includes("--originkit");
  const migrated = [];
  const toDelete = [];

  // 按组收集
  const groupEntries = {};
  for (const [top, group] of Object.entries(GROUPS)) {
    if (onlyGroup && group !== onlyGroup) continue;
    const dir = path.join(SRC, top);
    const files = collectRoutes(dir);
    if (!files.length) continue;
    groupEntries[group] = (groupEntries[group] || []).concat(
      files.map((f) => {
        const rel = relKey(f, top); // auth/login
        const sub = rel.slice(top.length + 1); // login（根级 route.ts → ""）
        return { group, top, file: f, rel, sub, modPath: sub || "_root", key: sub, methods: methodsOf(f) };
      }),
    );
  }
  // other（兜底）
  if (!onlyGroup || onlyGroup === "other") {
    const files = [];
    for (const top of OTHER_TOP) {
      const dir = path.join(SRC, top);
      if (fs.existsSync(dir)) {
        for (const f of collectRoutes(dir)) files.push(f);
      }
    }
    if (files.length) {
      groupEntries.other = files.map((f) => {
        const rel = relKey(f, ""); // account/ima
        const top = rel.split("/")[0];
        const sub = rel.slice(top.length + 1); // ima
        return { group: "other", top, file: f, rel, sub, modPath: rel, key: rel, methods: methodsOf(f) };
      });
    }
  }

  // 1) 复制 handler 到 lib/api-handlers/<group>/<modPath>.ts（先清目标目录保证幂等）
  for (const [group, entries] of Object.entries(groupEntries)) {
    fs.rmSync(path.join(DST, group), { recursive: true, force: true });
    for (const e of entries) {
      const dst = path.join(DST, group, `${e.modPath}.ts`);
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.copyFileSync(e.file, dst);
      migrated.push({ from: e.file.replace(ROOT + path.sep, ""), to: dst.replace(ROOT + path.sep, "") });
    }
    // 2) 生成 catch-all 分发器（other 组 → 顶层 app/api/[[...path]]；固定组 → app/api/<top>/[[...path]]）
    const top = entries[0].top;
    const dispatcherDir = group === "other" ? path.join(SRC, "[[...path]]") : path.join(SRC, top, "[[...path]]");
    fs.mkdirSync(dispatcherDir, { recursive: true });
    const ds = dispatcherSource(group, entries);
    fs.writeFileSync(path.join(dispatcherDir, "route.ts"), ds, "utf8");
    migrated.push({
      from: "(generated)",
      to: path.relative(ROOT, path.join(dispatcherDir, "route.ts")).replaceAll(path.sep, "/"),
    });
    // 3) 记录待删除原文件
    for (const e of entries) toDelete.push(e.file);
  }

  // originkit 合并（genius/wexo 两个 catch-all → 一个，按 path[0] 分发）
  if (doOriginkit && !onlyGroup) {
    const genius = path.join(SRC, "originkit", "genius", "[[...path]]", "route.ts");
    const wexo = path.join(SRC, "originkit", "wexo", "[[...path]]", "route.ts");
    const gSrc = fs.existsSync(genius) ? fs.readFileSync(genius, "utf8") : null;
    const wSrc = fs.existsSync(wexo) ? fs.readFileSync(wexo, "utf8") : null;
    const outDir = path.join(SRC, "originkit", "[[...path]]");
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(
      path.join(outDir, "route.ts"),
      `// AUTO-GENERATED by scripts/migrate-api-catchall.mjs — originkit genius/wexo 合并
import { NextRequest, NextResponse } from "next/server";
import { createStaticSiteHandler } from "@/lib/static-site-handler";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const genius = createStaticSiteHandler("genius");
const wexo = createStaticSiteHandler("wexo");

export async function GET(req: NextRequest, ctx: { params: Promise<{ path: string[] }> }) {
  const { path } = await ctx.params;
  if (path[0] === "genius") return genius(req, { params: Promise.resolve({ path: path.slice(1) }) });
  if (path[0] === "wexo") return wexo(req, { params: Promise.resolve({ path: path.slice(1) }) });
  return NextResponse.json({ error: "not_found", message: "整站模板不存在" }, { status: 404 });
}
`,
      "utf8",
    );
    if (gSrc) toDelete.push(genius);
    if (wSrc) toDelete.push(wexo);
    migrated.push({ from: "(generated)", to: "app/api/originkit/[[...path]]/route.ts" });
  }

  console.log("=== MIGRATED ===");
  for (const m of migrated) console.log(`  ${m.from}  →  ${m.to}`);
  console.log(`\n=== TO DELETE (${toDelete.length}) ===`);
  for (const d of toDelete) console.log("  " + d.replace(ROOT + path.sep, ""));
  fs.writeFileSync(
    path.join(ROOT, "scripts", ".migrate-delete-list.json"),
    JSON.stringify(toDelete.map((d) => d.replace(ROOT + path.sep, "")), null, 2),
    "utf8",
  );
  console.log(`\n删除清单已写入 scripts/.migrate-delete-list.json`);
}

run();
