// 作为交付工程包里的 SECURITY.md 下发，供用户在后续开发中作为硬约束参考。

export function buildSecurityGuideMd(): string {
  return `# 安全开发注意事项（SECURITY）

> 通用安全开发清单，与本项目技术栈无关，**任何项目上线前都应逐项核对**。下列项不是建议，是硬约束。

## 1. 鉴权

- 所有会**写数据或读敏感数据**的接口必须鉴权，不允许匿名调用（尤其是文件写入、删除类接口）。
- 用成熟的 JWT / session 方案；签名 secret 必须来自环境变量，**禁止在代码里写死回退值**（否则任何人可伪造凭证）。
- 资源按「所有权」校验：越权返回 403/404，不泄露资源是否存在。

## 2. 限流与防刷

- 登录 / 注册接口必须限流，防止暴力破解与撞库。
- AI / 付费 / 高成本接口必须限流，防止额度或账单被匿名刷爆。
- 单实例部署可用内存限流；多实例 / 生产环境接 Redis 等共享存储（内存限流在横向扩容后失效）。

## 3. 密钥管理

- 密钥只走服务端环境变量（.env），**绝不进前端 bundle**。
- 绝不写进代码、配置文件、zip 交付物、README 示例。
- 仓库内定期用正则扫描明文密钥（如 \`sk-\`、\`cmp_live_\`、\`AKIA\` 等常见前缀）。

## 4. 输入与注入

- 所有请求体用 zod 等 schema 校验，不接受未校验输入。
- 数据库访问走 ORM 参数化，**禁止字符串拼接 SQL**。
- 文件路径做白名单 + \`path.resolve\` 校验，防路径穿越（\`../\` 逃逸）。

## 5. 错误处理

- 错误响应**不要回显**第三方（LLM / 数据库）原始响应、堆栈、内部路径。
- 统一 try/catch，对外只返回通用错误码，细节只进服务端日志。

## 6. 其它

- 数据库 schema 变更走迁移，不要手动改库。
- 表单写操作加 CSRF 防护；cookie 用 \`httpOnly\` + \`sameSite\`，生产环境 \`secure\`。
- 生产环境强制 HTTPS。

## 7. 上线前自检

- [ ] 无匿名可写的敏感接口
- [ ] 登录 / 注册 / AI 接口均有限流
- [ ] 无明文密钥出现在前端 bundle / 仓库 / 交付物
- [ ] 错误响应不含内部细节
- [ ] 数据库有迁移体系，空库可一键建表
`;
}
