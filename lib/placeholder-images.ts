/** B 层：取第 idx 张池图 URL（Picsum 确定性 id，任意 /w/h）。blur=0..10，grayscale 可选。 */
export function poolImage(
  idx: number,
  opts: { w?: number; h?: number; grayscale?: boolean; blur?: number } = {},
): string {
  const id = POOL_IDS[((idx % POOL_IDS.length) + POOL_IDS.length) % POOL_IDS.length];
  const w = opts.w ?? 900;
  const h = opts.h ?? 620;
  const q = [
    opts.grayscale ? "grayscale" : "",
    typeof opts.blur === "number" ? `blur=${opts.blur}` : "",
  ]
    .filter(Boolean)
    .join("&");
  return `https://picsum.photos/id/${id}/${w}/${h}${q ? `?${q}` : ""}`;
}

