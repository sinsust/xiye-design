/* 按「区块角色」统一取图：自动选层 + 配好宽高                            */
/* ------------------------------------------------------------------ */

export type PlaceholderRole =
  | "hero"      // 首屏大图：A 层精图（要设计感），宽幅
  | "brand"     // 品牌视觉 / 封面：A 层精图，方形
  | "gallery"   // 画廊 / 走马：A 层精图（签名视觉）
  | "feature"   // 功能 / 场景配图：B 层大池
  | "work"      // 作品集 / 案例封面：B 层大池
  | "case"      // 案例过程图：B 层大池
  | "blog"      // 博客 / 文章：B 层大池，16:10
  | "product"   // 商品主图：B 层大池，竖图
  | "thumb"     // 网格缩略图：B 层大池，方形
  | "avatar"    // 团队 / 头像：B 层大池，竖版
  | "about"     // 品牌故事 / 环境：B 层大池，竖版

/** 哪些角色走 A 层精图（AI 风格）；其余走 B 层大池。 */
const TIER_A_ROLES: ReadonlySet<PlaceholderRole> = new Set<PlaceholderRole>([
  "hero",
  "brand",
  "gallery",
]);

const ROLE_SIZES: Record<PlaceholderRole, { w: number; h: number }> = {
  hero: { w: 1600, h: 900 },
  brand: { w: 900, h: 900 },
  gallery: { w: 800, h: 800 },
  feature: { w: 1200, h: 800 },
  work: { w: 900, h: 640 },
  case: { w: 900, h: 620 },
  blog: { w: 1000, h: 640 },
  product: { w: 800, h: 1000 },
  thumb: { w: 480, h: 480 },
  avatar: { w: 400, h: 500 },
  about: { w: 900, h: 1000 },
};

/**
 * 统一入口：按区块角色取图。自动选层（签名视觉→精图 / 大批量→池）+ 配好该角色的宽高。
 * 可用 opts.w/h 覆盖默认尺寸（适合容器固定比例的场合）。
 */
export function resolvePlaceholder(
  role: PlaceholderRole,
  idx: number,
  opts: { w?: number; h?: number; grayscale?: boolean; blur?: number } = {},
): string {
  const size = ROLE_SIZES[role] ?? ROLE_SIZES.hero;
  if (TIER_A_ROLES.has(role)) {
    return premiumImage(idx, { w: opts.w ?? size.w });
  }
  return poolImage(idx, {
    w: opts.w ?? size.w,
    h: opts.h ?? size.h,
    grayscale: opts.grayscale,
    blur: opts.blur,
  });
}