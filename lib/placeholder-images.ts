/** A 层：取第 index 张精图 URL（自动循环；默认 Cloudflare 侧宽度 900）。 */
export function premiumImage(index: number, opts: { w?: number } = {}): string {
  const id = PREMIUM_IDS[((index % PREMIUM_IDS.length) + PREMIUM_IDS.length) % PREMIUM_IDS.length];
  const w = opts.w ?? 900;
  return `${IMAGE_DELIVERY_BASE}/${id}/w=${w}`;
}

/** A 层：一次取 count 张精图（画廊 / 圆形走马等）。 */
export function premiumImages(count: number, opts: { w?: number } = {}): string[] {
  return Array.from({ length: Math.max(0, count) }, (_, i) => premiumImage(i, opts));
}

